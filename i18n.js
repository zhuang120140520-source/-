let currentLang = 'zh';
try {
  const saved = localStorage.getItem('weekend_outing_lang');
  if (Object.prototype.hasOwnProperty.call(I18N, saved)) currentLang = saved;
} catch (e) {}

function t(key) {
  return (I18N[currentLang] || I18N.zh)[key] ?? I18N.zh[key] ?? key;
}

function applyLang(lang) {
  currentLang = Object.prototype.hasOwnProperty.call(I18N, lang) ? lang : 'zh';
  try { localStorage.setItem('weekend_outing_lang', currentLang); } catch (e) {}
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === currentLang));
  if (window.onLangChange) window.onLangChange();
}

document.querySelectorAll('.lang-btn').forEach(btn => btn.addEventListener('click', () => applyLang(btn.dataset.lang)));
applyLang(currentLang);
